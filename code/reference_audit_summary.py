#!/usr/bin/env python3
"""reference_audit_summary.py -- R2, Reviewer 3 comment 2.
Consolidates the per-entry reference audit (data/reference_audit/*.json) and
the applied corrections (data/reference_corrections_R2.csv) into
data/reference_audit_R2.csv and response/refaudit_macros.tex."""
import csv, glob, json, os, re, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cited = set(re.findall(r'^@\w+\{([^,]+),', open(os.path.join(ROOT, 'references.bib'),
                                                 encoding='utf-8').read(), re.M))
aud = {}
for f in sorted(glob.glob(os.path.join(ROOT, 'data', 'reference_audit', '*.json'))):
    for e in json.load(open(f, encoding='utf-8')):
        aud[e['key']] = e
corr = list(csv.DictReader(open(os.path.join(ROOT, 'data',
                                             'reference_corrections_R2.csv'), encoding='utf-8')))
ck = collections.defaultdict(list)
for c in corr:
    ck[c['key']].append(c)
with open(os.path.join(ROOT, 'data', 'reference_audit_R2.csv'), 'w', newline='',
          encoding='utf-8') as fh:
    w = csv.writer(fh)
    w.writerow(['key', 'cited_in_R2', 'audit_status', 'fields_corrected',
                'verification_source', 'comment'])
    for k in sorted(set(aud) | cited):
        e = aud.get(k, {})
        st = e.get('status', 'NEW_R2' if k not in aud else '')
        w.writerow([k, int(k in cited), st,
                    '; '.join(sorted({c['field'] for c in ck.get(k, [])})),
                    e.get('source_url', ''), (e.get('comment') or '')[:300]])
# classify applied corrections
cls = collections.Counter()
keys_by = collections.defaultdict(set)
for c in corr:
    f, v = c['field'], c['new_value']
    if f == 'note':
        t = 'annotation'
    elif c['key'] == 'Boroumand2022AEarthquake' and f == 'pages':
        t = 'wrong_pages'
    elif f in ('pages', 'volume', 'number', 'month') and v != 'DELETE':
        t = 'locator'
    elif f == 'year':
        t = 'year'
    elif f == 'author':
        t = 'author'
    elif f in ('@type', 'booktitle', 'journal', 'series', 'publisher', 'address'):
        t = 'venue'
    elif f == 'title':
        t = 'title'
    else:
        t = 'other'
    keys_by[t].add(c['key'])
N = lambda t: len(keys_by[t] & cited)
st = collections.Counter(aud[k]['status'] for k in cited if k in aud)
L = ['% generated by code/reference_audit_summary.py',
     r'\newcommand{\RefN}{%d}' % len(cited),
     r'\newcommand{\RefChecked}{%d}' % (st['OK'] + st['EXISTS-OK'] + st['CORRECTED'] + st['PROBLEM']),
     r'\newcommand{\RefUnverified}{%d}' % st['UNVERIFIED'],
     r'\newcommand{\RefNotFound}{%d}' % st['NOT-FOUND'],
     r'\newcommand{\RefNotFoundCorpus}{%d}' % sum(1 for r in csv.DictReader(open(os.path.join(ROOT, 'data', 'unlocated_sources_R2.csv'))) if r['in_corpus'] == '1'),
     r'\newcommand{\RefCorrectedKeys}{%d}' % len({c['key'] for c in corr} & cited),
     r'\newcommand{\RefFixAnnotation}{%d}' % N('annotation'),
     r'\newcommand{\RefFixLocator}{%d}' % N('locator'),
     r'\newcommand{\RefFixWrongPages}{%d}' % N('wrong_pages'),
     r'\newcommand{\RefFixYear}{%d}' % N('year'),
     r'\newcommand{\RefFixAuthor}{%d}' % N('author'),
     r'\newcommand{\RefFixVenue}{%d}' % N('venue'),
     r'\newcommand{\RefFixTitle}{%d}' % N('title'),
     r'\newcommand{\RefRemoved}{%d}' % 3]
open(os.path.join(ROOT, 'response', 'refaudit_macros.tex'), 'w').write('\n'.join(L) + '\n')
print('\n'.join(L))
