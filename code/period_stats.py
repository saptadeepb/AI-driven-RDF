#!/usr/bin/env python3
"""period_stats.py -- R2: the method-family shares by publication period that
the abstract, Section 5.8 and the Conclusion quote were typed by hand in R1.
They are now computed here from data/master_extraction.csv (same periods as
Figure 15) and written to period_macros.tex."""
import csv, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = [r for r in csv.DictReader(open(os.path.join(ROOT, 'data',
     'master_extraction.csv'))) if r['study_type'] == 'Primary']
P = {'Early': (2007, 2015), 'Mid': (2016, 2020), 'Late': (2021, 2026)}
F = {'Stat': 'mf_statistical', 'ML': 'mf_ml', 'DL': 'mf_dl',
     'KB': 'mf_knowledge', 'OS': 'mf_optsim', 'GA': 'mf_genai'}
L = ['%% generated by code/period_stats.py -- do not edit']
for pn, (a, b) in P.items():
    S = [r for r in R if a <= int(r['year']) <= b]
    L.append(r'\newcommand{\per%sN}{%d}' % (pn, len(S)))
    for fn, col in F.items():
        v = 100 * sum(r[col] == '1' for r in S) / len(S)
        L.append(r'\newcommand{\per%s%s}{%.0f}' % (pn, fn, v))
open(os.path.join(ROOT, 'period_macros.tex'), 'w').write('\n'.join(L) + '\n')
print('\n'.join(L))

# R2: count of primary studies coded Qualitative/none (Section 7.1)
nq = sum(1 for r in R if r['performance_evidence'] == 'Qualitative/none')
with open(os.path.join(ROOT, 'period_macros.tex'), 'a') as fh:
    fh.write('\\newcommand{\\nqualitative}{%d}\n' % nq)
    fh.write('\\newcommand{\\nsingle}{%d}\n' % sum(1 for r in R if r['performance_evidence'] == 'Single-model metric'))
